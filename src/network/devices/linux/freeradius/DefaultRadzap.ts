export const RADZAP_PATH = '/usr/bin/radzap';

export const RADZAP_SCRIPT = [
  '#!/bin/sh',
  'usage() {',
  '\techo "Usage: radzap [options] server[:port] secret" >&2',
  '\techo "       -h Print usage help information."',
  '\techo "       -d raddb_directory: directory where radiusd.conf is located."',
  '\techo "       -D dict_directory: directory where the dictionaries are located."',
  '\techo "       -N nas_ip_address: IP address of the NAS to zap."',
  '\techo "       -P nas_port: NAS port that the user is logged into."',
  '\techo "       -u username: Name of user to zap (case insensitive)."',
  '\techo "       -U username: like -u, but case-sensitive."',
  '\techo "       -x Enable debugging output."',
  '\texit ${1:-0}',
  '}',
  '',
  'while test "$#" != "0"',
  'do',
  '  case $1 in',
  '      -h) usage;;',
  '      -d) OPTS="$OPTS -d $2";shift;shift;;',
  '      -D) OPTS="$OPTS -D $2";shift;shift;;',
  '      -N) NAS_IP_ADDR="-N $2";shift;shift;;',
  '      -P) NAS_PORT="-P $2";shift;shift;;',
  '      -u) USER_NAME="-u $2";shift;shift;;',
  '      -U) USER_NAME="-U $2";shift;shift;;',
  '      -x) DEBUG="-x";shift;;',
  '      *) break;;',
  '  esac',
  'done',
  '',
  'if test "$#" != "2"; then',
  '    usage 1 >&2',
  'fi',
  '',
  'SERVER=$1',
  'SECRET=$2',
  '',
  'radwho -ZR $OPTS $NAS_IP_ADDR $NAS_PORT $USER_NAME | radclient $DEBUG $OPTS -f - $SERVER acct $SECRET',
  '',
].join('\n');
