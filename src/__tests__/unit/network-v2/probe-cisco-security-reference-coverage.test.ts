/**
 * Cisco IOS Security Command Reference (official_docs/cisco/ios-security): how many of the
 * documented commands the CiscoRouter shell recognises word for word. A command counts as
 * recognised when every word of its documented name is offered by `?` after the previous ones,
 * in the mode the book gives (user EXEC, privileged EXEC, global, interface and line
 * configuration; the other sub-modes are not measured).
 *
 * Measured on the index of 1989 entries: 1028 fall in a measured mode, 128 recognised, 644
 * recognised in part, 256 not at all. The floor below only goes up: a change that loses a
 * recognised command fails. The index is regenerated by scripts/cisco/extract_security_commands.py.
 */
import { it, expect } from 'vitest';
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CiscoRouter } from '@/network/devices/CiscoRouter';
import { EquipmentRegistry } from '@/network/equipment/EquipmentRegistry';

function modeOf(m: string | null): string {
  const s = (m ?? '').replace(/\s/g, '').toLowerCase();
  if (s.startsWith('globalconfiguration')) return 'config';
  if (s.startsWith('interfaceconfiguration')) return 'config-if';
  if (s.startsWith('privilegedexec')) return 'priv';
  if (s.startsWith('userexec')) return 'user';
  if (s.startsWith('lineconfiguration')) return 'config-line';
  if (s.startsWith('exec')) return 'priv';
  return 'other';
}

const RECOGNISED_FLOOR = 199;

it('the documented security commands the shell recognises never go down', async () => {
  EquipmentRegistry.resetInstance();
  const entries = JSON.parse(readFileSync(join(__dirname, '..', '..', '..', '..', 'official_docs', 'cisco', 'ios-security', 'commands-index.json'), 'utf8'));
  const r = new CiscoRouter('R1');
  const run = async (c: string) => String(await r.executeCommand(c));
  const enter = async (mode: string) => {
    await run('end'); await run('end');
    if (mode === 'user') { await run('disable'); return; }
    await run('enable');
    if (mode === 'priv') return;
    await run('configure terminal');
    if (mode === 'config-if') await run('interface GigabitEthernet0/0');
    if (mode === 'config-line') await run('line vty 0 4');
  };
  const out: unknown[] = [];
  for (const e of entries) {
    const mode = modeOf(e.mode);
    const words = e.name.replace(/\(.*\)/g, '').trim().split(/\s+/).filter(Boolean);
    if (mode === 'other' || words.length === 0) { out.push({ ...e, status: 'other-mode', depth: 0, words: words.length }); continue; }
    await enter(mode);
    let depth = 0;
    for (let i = 0; i < words.length; i++) {
      const prefix = words.slice(0, i).join(' ');
      const help = await run(`${prefix} ?`.trim());
      if (/Invalid input|Unrecognized/.test(help)) break;
      const w = words[i].toLowerCase();
      const hit = help.split('\n').some((l) => l.trim().toLowerCase().split(/\s+/)[0] === w);
      if (!hit) break;
      depth++;
    }
    out.push({ book: e.book, name: e.name, mode, words: words.length, depth, status: depth === words.length ? 'full' : depth === 0 ? 'none' : 'partial' });
  }
  const recognised = (out as Array<{ status: string }>).filter((o) => o.status === 'full').length;
  if (process.env.CISCO_SECURITY_COVERAGE_DUMP && existsSync(process.env.CISCO_SECURITY_COVERAGE_DUMP)) {
    writeFileSync(process.env.CISCO_SECURITY_COVERAGE_DUMP + '/coverage.json', JSON.stringify(out));
  }
  expect(recognised).toBeGreaterThanOrEqual(RECOGNISED_FLOOR);
}, 900000);
