/*
 * head, tail, wc, cut, sort, uniq and tr accepted options they did not evaluate and
 * answered at exit status 0 whatever happened: `head -n2` (attached value) printed
 * the whole file, `-c`/`-n` accepted garbage, `cut` had no list validation, no `-z`,
 * no `--complement`/`--output-delimiter` semantics; `sort` took `-S 1M`/`-T dir`
 * as file names, ignored `-c`/`-C`/`-o`/`-m`/`-z`/`-k` errors and key syntax,
 * `uniq` had no `-D`/`--group`/option checks, `tr` worked line by line (so `-c`
 * and `\n` were wrong) and accepted missing operands, `wc` ignored `--total`,
 * `--files0-from` and the column width rule, `--help`/`--version` answered nothing,
 * errors went to stdout, and printf/echo byte escapes (`\303\251`) became two
 * characters instead of one UTF-8 character.
 *
 * Every expected string was produced by the real GNU coreutils 9.4 of the dev
 * container on the same files (words with seven lines, nums 1..10, z with NUL
 * separators, list0, symbolic links), by running the identical line in bash with
 * LC_ALL=C.UTF-8 (C collation). Ubuntu 22.04 ships 8.32; the options exercised
 * here behave alike. Output order is compared EXACTLY. NOT covered, because the
 * machines differ: the 9.4 vs 8.32 version banner, \`sort --debug\` (annotated
 * output), \`od\` (not implemented: three cases that piped through it were dropped),
 * stdin redirected from a regular file (\`wc - < f\`, whose column width real wc
 * takes from the file size) and the position of a diagnostic relative to the output
 * of a pipe (stderr is unbuffered there).
 *
 * Measured against the commit before the rewrite (worktree): 418 cases, 181 fall;
 * the 237 that pass either way are the ordinary invocations of each tool
 * (default sort, -n, -r, -u, -k, cut -d -f, uniq -c, tr a-z A-Z, wc -l...) that
 * already worked and serve as the witness that the lab is sound.
 */
