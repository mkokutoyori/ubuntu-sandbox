/*
 * link, unlink, pathchk, hostid, factor, tsort, base32 and basenc answered `command not found`
 * (base64 was the only member of the family): they are added, the base64 codec becomes the one
 * generic bit coder behind base64, base32 and every basenc encoding (padding rules, mid-stream
 * versus end-of-input failures, wrapping, -i), pathchk follows the portability checks of the
 * standard (-p, -P, component and path limits, the lstat-style failures), factor handles
 * arbitrary-size integers with exponents (-h), and tsort is a line-for-line port of tsort.c 9.4
 * (zero queue, loop detection and the arc it removes), checked against 40 random graphs.
 *
 * Every expected string was produced by the real GNU coreutils 9.4 of the dev container, by
 * running the identical line in bash with LC_ALL=C.UTF-8 (typographic quotes normalised, scratch
 * directory rewritten to /tmp/ff). NOT covered, because the machines differ: the version banner,
 * `hostid` (derived from the machine's address), and the stderr of an earlier command of a `;` list.
 *
 * Measured against the commit before (worktree): 237 cases; 233 fall (the commands did not exist),
 * 4 pass either way as witnesses (refusals the old shell also gave).
 */
