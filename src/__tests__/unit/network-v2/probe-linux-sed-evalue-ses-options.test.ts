describe('sed evaluates what it accepts and refuses what it cannot parse, like GNU sed 4.9', () => {
  it.each(SCRIPTS.map((row) => [JSON.stringify(row[0]) + (row[1] === null ? '' : ` < ${JSON.stringify(row[1])}`), row] as const))('%s', async (_name, row) => {
    const machine = await lab();
    await machine.executeCommand(SETUP);
    expect(trimEnd(await machine.executeCommand(shellFor(row[0], row[1])))).toBe(row[2]);
  });

  it.each(PIPELINES.map((row) => [row[0], row] as const))('%s', async (_name, row) => {
    const machine = await lab();
    await machine.executeCommand(SETUP);
    expect(trimEnd(await machine.executeCommand(row[0]))).toBe(row[1]);
  });
});
