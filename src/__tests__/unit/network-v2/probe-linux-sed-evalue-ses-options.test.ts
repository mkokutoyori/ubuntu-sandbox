const quote = (word: string): string => `'${word.replace(/'/g, "'\\''")}'`;

function shellFor(args: readonly string[], stdin: string | null): string {
  const sed = `sed ${args.map(quote).join(' ')}`;
  const feed = stdin === null ? sed : `printf %s ${quote(stdin)} | ${sed}`;
  return `${feed} 2>&1; echo "[$?]"; ${TAIL}`;
}

