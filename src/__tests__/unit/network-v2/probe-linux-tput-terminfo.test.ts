/*
 * tput knew cols, lines and eight capability names it did not even print (clear, init, bold... answered an empty string) and refused every other name with
 * 'unknown terminfo capability'. tty/Tput.ts is now tput of ncurses over a terminfo database captured from the dev container (19 terminals: linux, xterm,
 * xterm-256color, vt100, screen, tmux, rxvt, ansi, dumb...), with the full tparm stack machine (%p %P %g %' %{ %l arithmetic and bit operators, comparisons, %i, the
 * %? %t %e %; conditionals, %d %o %x %X %s %c with flags, width and precision), $<..> padding removed, parameters taken from the leading numeric words, the raw string
 * when no word follows, boolean (exit 1 when false), numeric (-1 when absent) and string capabilities (exit 1 when undefined), -T, -S, -V, -x (no E3 scrollback
 * clear), longname, clear with its extended E3, the usage, 'unknown terminal' (3), 'No value for $TERM' (2) and 'unknown terminfo capability' (4, aborting the run).
 *
 * Every expected string was produced by the real tput of ncurses 6.4 of the dev container (version rewritten to the simulated 6.3.20211021); a stratified sample of
 * the 1719 cases (every capability of ten terminals, with and without parameters) was compared in full and agreed on all but the artifacts below. Not modelled
 * (TODO.md): bytes above 0x7f (acsc) come out UTF-8 encoded, init/reset skip the tab setting, and the cols/lines of a terminal given with -T come from terminfo only.
 *
 * Measured against the commit before (worktree): 579 of 579 cases fall: the old tput knew cols, lines and a handful of names it did not print, so no case passes either way
 * (the lab itself is vouched for by the other probes, which run the same harness).
 */
