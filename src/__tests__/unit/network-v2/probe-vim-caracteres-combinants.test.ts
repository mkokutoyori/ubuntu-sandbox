function substituteWith(text: string, pattern: string): string {
  const vim = new VimEngine(new InMemoryEditorFsContext({ '/tmp/f': 'x\n' }), '/tmp/f', 'x\n', false, 'vim', 'root');
  const quote = (value: string): string => `'${value.replace(/'/g, "''")}'`;
  const keys = `:echo substitute(${quote(text)}, ${quote(pattern)}, '[&]', 'g')\n`;
  for (const character of [...keys]) vim.applyKey(character === '\n' ? editorKey('Enter') : editorKey(character));
  return vim.message;
}

describe('caracteres combinants dans les motifs', () => {
  CASES.forEach(([text, pattern, expected]) => {
    it(`${JSON.stringify(text)} ~ ${JSON.stringify(pattern)}`, () => {
      expect(substituteWith(text, pattern)).toBe(expected);
    });
  });
});
