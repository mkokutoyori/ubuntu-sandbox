/*
 * cp, mv, ln, rm, rmdir, mkdir, chmod, cat, basename, dirname, seq, echo and printf
 * accepted options they did not evaluate or answered the wrong text: `cp words words`
 * copied a file onto itself, `cp --backup=numbered` / `-S` / `--parents` /
 * `--reflink` / `--sparse` / `--remove-destination` / `--attributes-only` were
 * dropped or unknown, `--preserve=bogus` was accepted, `mv` ignored `-b`/`-S`,
 * moved a directory into itself and did not decline at EOF, `rm -i/-I/-d/-v` and
 * `rmdir -p/-v` had no semantics, `mkdir -m` took only octal, `chmod` mishandled
 * `X`, `=`, `u=g`, special bits on directories and `-c/-v/--reference`, `ln` lacked
 * `-r/-t/-T/-b/-S`, `cat` had no `-A/-b/-s/-T/-v` and stopped at the first missing file,
 * `seq` had no decimal arithmetic, `-w`, `-f` or error texts, `basename`/`dirname`
 * ignored `-a/-s/-z`, errors went to stdout and exit statuses were 0.
 *
 * Every expected string was produced by the real GNU coreutils 9.4 of the dev
 * container on the same files, by running the identical line in bash with
 * LC_ALL=C.UTF-8; typographic quotes are normalised on both sides. Ubuntu 22.04
 * ships 8.32. NOT covered, because the machines differ: the version banner,
 * `--help` text, the `-n` exit status that 9.x changed (mv -n, cp -n warning), the
 * prompts of `-i`/`-I` whose stderr the harness does not capture on the real side,
 * readdir order of `rm -rv`, root versus user ownership, the "line 1:" prefix bash
 * adds in a script, and `od` (not implemented).
 *
 * Measured against the commit before the rewrite (worktree): 317 cases, 106 fall; the 211 that pass either way are the ordinary
 * invocations (cp/mv/ln/rm/mkdir/chmod/cat/seq without exotic options, the plain error
 * texts that already matched) and serve as the witness that the lab is sound.
 */
