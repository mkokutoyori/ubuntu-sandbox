export function modpGroup(id: number): ModpGroup | undefined {
  return MODP_GROUPS.get(id);
}

export interface ModpKeyPair {
  readonly group: ModpGroup;
  readonly privateKey: bigint;
  readonly publicKey: bigint;
}

const PRIVATE_EXPONENT_BITS = 256;

export function generateModpKeyPair(
  group: ModpGroup, randomness?: Uint8Array,
): ModpKeyPair {
  const bytes = randomness ?? randomExponent();
  let secret = 0n;
  for (const byte of bytes) secret = (secret << 8n) | BigInt(byte);
  if (secret < 2n) secret += 2n;

  return {
    group,
    privateKey: secret,
    publicKey: modPow(group.generator, secret, group.prime),
  };
}

export function modpSharedSecret(own: ModpKeyPair, peerPublic: bigint): bigint | null {
  const p = own.group.prime;
  if (peerPublic <= 1n || peerPublic >= p - 1n) return null;
  return modPow(peerPublic, own.privateKey, p);
}

export function modpToHex(value: bigint): string {
  const raw = value.toString(16);
  return raw.length % 2 === 0 ? raw : `0${raw}`;
}

export function modpFromHex(hex: string): bigint {
  return BigInt(`0x${hex}`);
}

function randomExponent(): Uint8Array {
  const out = new Uint8Array(PRIVATE_EXPONENT_BITS / 8);
  for (let i = 0; i < out.length; i++) out[i] = Math.floor(Math.random() * 256);
  return out;
}
