const SUBKEY_STEP = 0x01010101;

export interface TwofishSchedule {
  readonly subkeys: Uint32Array;
  readonly sVector: readonly number[];
  readonly keyWords: number;
}

function multiply(a: number, b: number, polynomial: number): number {
  let result = 0;
  let left = a;
  let right = b;
  while (right > 0) {
    if (right & 1) result ^= left;
    left <<= 1;
    if (left & 0x100) left ^= polynomial;
    right >>>= 1;
  }
  return result;
}

function rotl(value: number, bits: number): number {
  return ((value << bits) | (value >>> (32 - bits))) >>> 0;
}

function rotr(value: number, bits: number): number {
  return ((value >>> bits) | (value << (32 - bits))) >>> 0;
}

function byteOf(word: number, index: number): number {
  return (word >>> (8 * index)) & 0xff;
}

function mdsMultiply(bytes: readonly number[]): number {
  let word = 0;
  for (let row = 0; row < 4; row++) {
    let value = 0;
    for (let column = 0; column < 4; column++) value ^= multiply(MDS_MATRIX[row][column], bytes[column], MDS_POLYNOMIAL);
    word |= value << (8 * row);
  }
  return word >>> 0;
}

function substitute(x: number, key: readonly number[], keyWords: number): number {
  const y = [byteOf(x, 0), byteOf(x, 1), byteOf(x, 2), byteOf(x, 3)];
  if (keyWords === 4) {
    y[0] = Q1[y[0]] ^ byteOf(key[3], 0);
    y[1] = Q0[y[1]] ^ byteOf(key[3], 1);
    y[2] = Q0[y[2]] ^ byteOf(key[3], 2);
    y[3] = Q1[y[3]] ^ byteOf(key[3], 3);
  }
  if (keyWords >= 3) {
    y[0] = Q1[y[0]] ^ byteOf(key[2], 0);
    y[1] = Q1[y[1]] ^ byteOf(key[2], 1);
    y[2] = Q0[y[2]] ^ byteOf(key[2], 2);
    y[3] = Q0[y[3]] ^ byteOf(key[2], 3);
  }
  const mixed = [
    Q1[Q0[Q0[y[0]] ^ byteOf(key[1], 0)] ^ byteOf(key[0], 0)],
    Q0[Q0[Q1[y[1]] ^ byteOf(key[1], 1)] ^ byteOf(key[0], 1)],
    Q1[Q1[Q0[y[2]] ^ byteOf(key[1], 2)] ^ byteOf(key[0], 2)],
    Q0[Q1[Q1[y[3]] ^ byteOf(key[1], 3)] ^ byteOf(key[0], 3)],
  ];
  return mdsMultiply(mixed);
}

export function twofishExpandKey(key: Uint8Array): TwofishSchedule {
  if (key.length !== 16 && key.length !== 24 && key.length !== 32) throw new Error(`Twofish: key must be 16, 24 or 32 bytes (got ${key.length})`);
  const keyWords = key.length / 8;
  const view = new DataView(key.buffer, key.byteOffset, key.byteLength);
  const even: number[] = [];
  const odd: number[] = [];
  const sVector: number[] = [];
  for (let index = 0; index < keyWords; index++) {
    even.push(view.getUint32(index * 8, true));
    odd.push(view.getUint32(index * 8 + 4, true));
    let word = 0;
    for (let row = 0; row < 4; row++) {
      let value = 0;
      for (let column = 0; column < 8; column++) value ^= multiply(RS_MATRIX[row][column], key[index * 8 + column], RS_POLYNOMIAL);
      word |= value << (8 * row);
    }
    sVector[keyWords - 1 - index] = word >>> 0;
  }
  const subkeys = new Uint32Array(40);
  for (let index = 0; index < 20; index++) {
    const a = substitute(Math.imul(2 * index, SUBKEY_STEP) >>> 0, even, keyWords);
    const b = rotl(substitute(Math.imul(2 * index + 1, SUBKEY_STEP) >>> 0, odd, keyWords), 8);
    subkeys[2 * index] = (a + b) >>> 0;
    subkeys[2 * index + 1] = rotl((a + 2 * b) >>> 0, 9);
  }
  return { subkeys, sVector, keyWords };
}

function g(schedule: TwofishSchedule, x: number): number {
  return substitute(x, schedule.sVector, schedule.keyWords);
}

function functionF(schedule: TwofishSchedule, r0: number, r1: number, round: number): [number, number] {
  const t0 = g(schedule, r0);
  const t1 = g(schedule, rotl(r1, 8));
  return [(t0 + t1 + schedule.subkeys[2 * round + 8]) >>> 0, (t0 + 2 * t1 + schedule.subkeys[2 * round + 9]) >>> 0];
}

export function twofishEncryptBlock(schedule: TwofishSchedule, block: Uint8Array): Uint8Array {
  const view = new DataView(block.buffer, block.byteOffset, block.byteLength);
  let r0 = (view.getUint32(0, true) ^ schedule.subkeys[0]) >>> 0;
  let r1 = (view.getUint32(4, true) ^ schedule.subkeys[1]) >>> 0;
  let r2 = (view.getUint32(8, true) ^ schedule.subkeys[2]) >>> 0;
  let r3 = (view.getUint32(12, true) ^ schedule.subkeys[3]) >>> 0;
  for (let round = 0; round < 16; round++) {
    const [f0, f1] = functionF(schedule, r0, r1, round);
    const next2 = rotr((r2 ^ f0) >>> 0, 1);
    const next3 = (rotl(r3, 1) ^ f1) >>> 0;
    r2 = r0;
    r3 = r1;
    r0 = next2;
    r1 = next3;
  }
  const out = new Uint8Array(TWOFISH_BLOCK_SIZE);
  const outView = new DataView(out.buffer);
  outView.setUint32(0, (r2 ^ schedule.subkeys[4]) >>> 0, true);
  outView.setUint32(4, (r3 ^ schedule.subkeys[5]) >>> 0, true);
  outView.setUint32(8, (r0 ^ schedule.subkeys[6]) >>> 0, true);
  outView.setUint32(12, (r1 ^ schedule.subkeys[7]) >>> 0, true);
  return out;
}

export function twofishDecryptBlock(schedule: TwofishSchedule, block: Uint8Array): Uint8Array {
  const view = new DataView(block.buffer, block.byteOffset, block.byteLength);
  let r0 = (view.getUint32(8, true) ^ schedule.subkeys[6]) >>> 0;
  let r1 = (view.getUint32(12, true) ^ schedule.subkeys[7]) >>> 0;
  let r2 = (view.getUint32(0, true) ^ schedule.subkeys[4]) >>> 0;
  let r3 = (view.getUint32(4, true) ^ schedule.subkeys[5]) >>> 0;
  for (let round = 15; round >= 0; round--) {
    const [f0, f1] = functionF(schedule, r2, r3, round);
    const previous2 = (rotl(r0, 1) ^ f0) >>> 0;
    const previous3 = rotr((r1 ^ f1) >>> 0, 1);
    r0 = r2;
    r1 = r3;
    r2 = previous2;
    r3 = previous3;
  }
  const out = new Uint8Array(TWOFISH_BLOCK_SIZE);
  const outView = new DataView(out.buffer);
  outView.setUint32(0, (r0 ^ schedule.subkeys[0]) >>> 0, true);
  outView.setUint32(4, (r1 ^ schedule.subkeys[1]) >>> 0, true);
  outView.setUint32(8, (r2 ^ schedule.subkeys[2]) >>> 0, true);
  outView.setUint32(12, (r3 ^ schedule.subkeys[3]) >>> 0, true);
  return out;
}
