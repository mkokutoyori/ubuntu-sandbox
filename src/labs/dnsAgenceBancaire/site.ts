const page = (title: string, description: string, body: string[], depth = 0): string => {
  const base = depth === 0 ? '' : '../'.repeat(depth);
  return [
    '<!DOCTYPE html>',
    '<html lang="fr">',
    '<head>',
    '  <meta charset="utf-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1">',
    `  <title>${title} - Banque Horizon</title>`,
    `  <meta name="description" content="${description}">`,
    `  <link rel="stylesheet" href="${base}css/site.css">`,
    `  <script defer src="${base}js/app.js"></script>`,
    '</head>',
    '<body>',
    '  <header class="bandeau">',
    `    <a class="marque" href="${base}index.html">Banque Horizon</a>`,
    '    <nav>',
    `      <a href="${base}produits/comptes.html">Comptes</a>`,
    `      <a href="${base}produits/credits.html">Credits</a>`,
    `      <a href="${base}produits/epargne.html">Epargne</a>`,
    `      <a href="https://agences.${PUBLIC_DOMAIN}/">Agences</a>`,
    `      <a class="bouton" href="https://ebanking.${PUBLIC_DOMAIN}/">E-banking</a>`,
    '    </nav>',
    '  </header>',
    '  <main>',
    ...body.map((line) => `    ${line}`),
    '  </main>',
    '  <footer>',
    '    <p>Banque Horizon S.A. - Agence Akwa, Douala - Serveur <span data-serveur>WEB-BANK</span></p>',
    `    <p><a href="${base}contact.html">Contact</a> - <a href="${base}mentions-legales.html">Mentions legales</a></p>`,
    '  </footer>',
    '</body>',
    '</html>',
  ].join('\n');
};

