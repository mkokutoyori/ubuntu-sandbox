PRELUDE = 'exec 2>/dev/null; rm -rf /tmp/w; mkdir -p /tmp/w; cd /tmp/w; '

def main():
    cases = []
    for script in SCRIPTS:
        run = subprocess.run(['bash', '-c', PRELUDE + script], capture_output=True, text=True, env={'PATH': os.environ['PATH'], 'HOME': '/home/user'}, timeout=20, stdin=subprocess.DEVNULL)
        cases.append({'script': script, 'stdout': run.stdout, 'status': run.returncode})
    version = subprocess.run(['bash', '--version'], capture_output=True, text=True).stdout.split('\n')[0]
    json.dump({'bash': version, 'cases': cases}, open(sys.argv[1], 'w'), indent=1)

if __name__ == '__main__':
    main()
