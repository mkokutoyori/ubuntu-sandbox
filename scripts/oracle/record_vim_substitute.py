#!/usr/bin/env python3
"""Record `:s` and its relatives from a real vim.

usage: record_vim_substitute.py out.json

Every case runs in its own vim process, typed through feedkeys(..., 'xt') so that the commands see
KeyTyped as an interactive session does (the 'report' threshold and the "Backwards range given" prompt depend on it),
and a vim carries no pattern, mark or substitute-string state from one case to the next.

Each case is a buffer, some setup commands, a start line and one ex command (or normal-mode keys).  A
headless `vim -u NONE -N -es` runs it and keeps the buffer, the cursor (line, byte column), the error,
what the command printed (`execute()`), the last search pattern (`@/`) and the buffer after `undo`.
The corpus covers the replacement escapes, patterns that span lines, ranges, counts, flags, the repeat
forms (`:&`, `:&&`, `:~`, `&`, `g&`), the 'report' threshold and the expression replacement `\\=` (operators,
numbers, floats, strings, lists, dictionaries, lambdas, builtin functions, and the errors they raise).

A headless vim runs in Ex mode, where an empty command line moves the cursor down one line; a chain
ending in `|` therefore records no empty step.
"""
import concurrent.futures, json, os, re, subprocess, sys, tempfile

SCRIPT = r"""
set nocompatible
set encoding=utf-8
let cases = json_decode(join(readfile($CASES), ''))
let out = []
for c in cases
  silent %delete _
  call setline(1, c.lines)
  set noignorecase nosmartcase wrapscan report=2 nogdefault magic
  for line in c.setup
    try
      execute line
    catch
    endtry
  endfor
  call cursor(c.start, 1)
  let v:errmsg = ''
  let r = {'id': c.id}
  let &undolevels = &undolevels
  let before = changenr()
  let r.output = ''
  for step in c.steps
    let v:errmsg = ''
    redir => typed
    silent! call feedkeys(step, 'xt')
    redir END
    let r.output = typed
    if c.abort && v:errmsg != ''
      break
    endif
  endfor
  let r.lines = getline(1, '$')
  let r.pos = [line('.'), col('.')]
  let r.err = v:errmsg
  let r.search = @/
  let &undolevels = &undolevels
  let r.undone = getline(1, '$')
  let attempts = 0
  while changenr() > before && attempts < 20
    silent! undo
    let attempts += 1
    let r.undone = getline(1, '$')
  endwhile
  call add(out, r)
endfor
call writefile([json_encode(out)], $OUT)
qa!
"""

