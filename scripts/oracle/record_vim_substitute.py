def case_list():
    cases = []

    def add(prefix, lines, cmd, setup=None, start=1, keys=None, ic=False):
        entry = {"id": "%s-%d" % (prefix, len(cases)), "lines": lines, "setup": (["set ic"] if ic else []) + (setup or []), "start": start}
        if keys is not None:
            entry["keys"] = keys
            entry["steps"] = list(keys)
            entry["abort"] = False
        else:
            entry["cmd"] = cmd
            parts = [part for part in cmd.split("|") if part.strip() != ""] if cmd in CHAINS else [cmd]
            entry["steps"] = [":" + part.strip() + "\r" for part in parts]
            entry["abort"] = len(parts) > 1
            if backwards(cmd):
                entry["steps"][-1] += "y"
        cases.append(entry)

    for ti, lines in enumerate(TEXTS):
        for cmd in ESCAPES:
            add("es%d" % ti, lines, cmd)
        for cmd in MULTILINE:
            add("ml%d" % ti, lines, cmd)
            add("ml%d" % ti, lines, cmd, start=3)
        for cmd in FLAGS:
            add("fl%d" % ti, lines, cmd)
            add("fl%d" % ti, lines, cmd, start=3)
        for cmd in RANGE_CASES:
            add("rg%d" % ti, lines, cmd, start=2)
        for setup, commands in REPORT_SETUP:
            for cmd in commands:
                add("rp%d" % ti, lines, cmd, setup=setup)
        for setup, commands in TILDE_SETUP:
            for cmd in commands:
                add("tl%d" % ti, lines, cmd, setup=setup)
        for setup, commands in BOUNDARY_SETUP:
            for cmd in commands:
                add("bd%d" % ti, lines, cmd, setup=setup)
        for keys in NORMAL:
            add("nm%d" % ti, lines, None, keys=keys)
        if ti in (1, 3):
            for cmd in EXPRESSIONS_PER_TEXT:
                add("ey%d" % ti, lines, cmd)
        if ti == 0:
            for cmd in EXPRESSIONS:
                add("ex%d" % ti, lines, cmd)
            for cmd in EXPRESSIONS_IGNORECASE:
                add("xi%d" % ti, lines, cmd, ic=True)
        for cmd in ("%s/o/0/g", "%s/e/\\r/g", "%s/\\n//", "%s/O/0/g", "%s/\\w\\+/\\u&/g"):
            add("ic%d" % ti, lines, cmd, ic=True)
    return cases


def backwards(command):
    match = re.match(r"^(\d+),(\d+)", command or "")
    return match is not None and int(match.group(1)) > int(match.group(2))


